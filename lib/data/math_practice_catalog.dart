  static List<QuestionModel> questionsFor(String topic) {
    return [
      ...questions.where((question) => question.topic == topic),
      ...(_additionalByTopic[topic] ?? const <QuestionModel>[]),
    ];
  }

  static List<QuestionModel> questionsForLesson(String lessonId) {
    final topic = topicByLessonId[lessonId];
    if (topic == null) return const [];
    final pool = List<QuestionModel>.from(questionsFor(topic));
    pool.shuffle(Random());
    return pool.take(min(10, pool.length)).toList();
  }
